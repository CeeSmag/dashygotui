package guard_test

import (
	"go/parser"
	"go/token"
	"strings"
	"testing"

	"github.com/CeeSmag/dashygotui/internal/guard"
)

const testState = "example.com/app/dashboard.State"

// valuePackage is a small addons package in the value form.
func valuePackage(t *testing.T) []guard.Source {
	t.Helper()
	return []guard.Source{
		src(t, addonDir+"doc.go", "// Package addons holds the features.\npackage addons\n\n//go:generate go tool dashygotui gen -state "+testState+"\n"),
		src(t, addonDir+"widget_system.go", `package addons

import "example.com/app/dashboard"

var system = dashboard.Widget{Key: "system"}
`),
		src(t, addonDir+"opt_backup.go", `package addons

import "example.com/app/dashboard"

var backup = dashboard.Option{Key: "backup"}

var backupView = dashboard.View{ID: "backup"}
`),
	}
}

// generated parses the generated list for srcs as a source of the package.
func generated(t *testing.T, srcs []guard.Source) guard.Source {
	t.Helper()
	out, err := guard.AddonList(srcs, testState)
	if err != nil {
		t.Fatal(err)
	}
	return src(t, addonDir+guard.GenFile, string(out))
}

func TestAddonListListsEveryValueInFileOrder(t *testing.T) {
	t.Parallel()
	out, err := guard.AddonList(valuePackage(t), testState)
	if err != nil {
		t.Fatal(err)
	}
	want := `// Code generated by dashygotui gen -state example.com/app/dashboard.State; DO NOT EDIT.

package addons

import (
	"github.com/CeeSmag/dashygotui"

	dashboard "example.com/app/dashboard"
)

// All returns every addon declared in this package, in file order, each with
// the place it is declared. Pass it to the dashboard in Config.Addons.
func All() []dashygotui.Addon[dashboard.State] {
	return []dashygotui.Addon[dashboard.State]{
		dashygotui.At[dashboard.State]("opt_backup.go:5", backup),
		dashygotui.At[dashboard.State]("opt_backup.go:7", backupView),
		dashygotui.At[dashboard.State]("widget_system.go:5", system),
	}
}
`
	if string(out) != want {
		t.Fatalf("generated list:\n%s\nwant:\n%s", out, want)
	}
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, guard.GenFile, out, parser.ParseComments)
	if err != nil {
		t.Fatal(err)
	}
	if got, ok := guard.GenState(f); !ok || got != testState {
		t.Fatalf("GenState = %q, %v", got, ok)
	}
}

func TestAddonListOfAnEmptyPackageCompilesToNothing(t *testing.T) {
	t.Parallel()
	out, err := guard.AddonList(valuePackage(t)[:1], testState) // only doc.go: every addon deleted
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(out), "return []dashygotui.Addon[dashboard.State]{}") {
		t.Fatalf("an empty list is not an empty literal:\n%s", out)
	}
}

func TestAddonListRejectsABadState(t *testing.T) {
	t.Parallel()
	for _, state := range []string{"", "State", "example.com/app.", "example.com/app/dashboard.state", "example.com/app/.State"} {
		if _, err := guard.AddonList(valuePackage(t), state); err == nil {
			t.Errorf("state %q accepted", state)
		}
	}
}

func TestAddonListAliasesTheStatePackage(t *testing.T) {
	t.Parallel()
	for state, want := range map[string]string{
		"example.com/app/v2.State":            "app.State",
		"example.com/my-app/dash-board.S":     "dash_board.S",
		"github.com/CeeSmag/dashygotui.Thing": "app.Thing",
	} {
		out, err := guard.AddonList(valuePackage(t), state)
		if err != nil {
			t.Fatal(err)
		}
		if !strings.Contains(string(out), "dashygotui.Addon["+want+"]") {
			t.Errorf("%s: the list does not use %s:\n%s", state, want, out)
		}
	}
}

func TestValueRules(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name string
		rel  string
		code string
		want string // space-separated rule IDs; "" for none
	}{
		{"an addon value", "opt_a.go", `package addons
var a = dashboard.Option{Key: "a"}`, ""},
		{"a generic addon value", "opt_a.go", `package addons
var a = stdaddons.Toggle[dashboard.State]{Key: "a"}`, ""},
		{"exported", "opt_a.go", `package addons
var A = dashboard.Option{Key: "a"}`, "A3"},
		{"not a literal", "opt_a.go", `package addons
var a = makeOption()`, "A3"},
		{"two in one spec", "opt_a.go", `package addons
var a, b = dashboard.Option{}, dashboard.Option{}`, "A3"},
		{"blank", "opt_a.go", `package addons
var _ = dashboard.Option{}`, "A3"},
		{"assigned in a callback", "opt_a.go", `package addons
var a = dashboard.Option{Do: func(c *dashboard.Ctx) { a.Label = "x" }}`, "A3"},
		{"a local that shadows it is fine", "opt_a.go", `package addons
var a = dashboard.Option{Do: func(c *dashboard.Ctx) { a := 1; a++ }}`, ""},
		{"init", "opt_a.go", `package addons
var a = dashboard.Option{Key: "a"}
func init() {}`, "A12"},
		{"a var in doc.go", "doc.go", `package addons
var x = dashboard.Option{}`, "A3"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			files := []guard.Source{src(t, addonDir+tt.rel, tt.code)}
			if tt.rel != "doc.go" {
				files = append(files, src(t, addonDir+"doc.go", "package addons"))
			}
			files = append(files, generated(t, files))
			if got := strings.Join(rules(guard.CheckApp(files).Findings), " "); got != tt.want {
				t.Fatalf("rules = %q, want %q: %v", got, tt.want, guard.CheckApp(files).Findings)
			}
		})
	}
}

func TestCurrentListIsClean(t *testing.T) {
	t.Parallel()
	files := valuePackage(t)
	files = append(files, generated(t, files))
	if rep := guard.CheckApp(files); len(rep.Findings) > 0 {
		t.Fatalf("a current list has findings (doc.go and the list must not trip A1 or A2): %v", rep.Findings)
	}
}

func TestStaleListIsA11(t *testing.T) {
	t.Parallel()
	files := valuePackage(t)
	gen := generated(t, files[:2]) // written before opt_backup.go was added
	rep := guard.CheckApp(append(files, gen))
	if got := strings.Join(rules(rep.Findings), " "); got != "A11" || !strings.Contains(rep.Findings[0].Msg, "stale") {
		t.Fatalf("findings = %v, want one stale A11", rep.Findings)
	}
}

func TestHandWrittenListIsA11(t *testing.T) {
	t.Parallel()
	files := append(valuePackage(t), src(t, addonDir+guard.GenFile, "package addons\nfunc All() {}"))
	rep := guard.CheckApp(files)
	if got := strings.Join(rules(rep.Findings), " "); got != "A11" || !strings.Contains(rep.Findings[0].Msg, "not written by dashygotui gen") {
		t.Fatalf("findings = %v", rep.Findings)
	}
}

func TestOneFileRuleExemptsTheGeneratedList(t *testing.T) {
	t.Parallel()
	got := guard.ChangeFindings([]guard.ChangedFile{
		{Path: "dashboard/addons/opt_new.go", Status: 'A'},
		{Path: "dashboard/addons/" + guard.GenFile, Status: 'M'},
		{Path: "dashboard/addons/" + guard.DocFile, Status: 'M'},
	})
	if len(got) != 0 {
		t.Fatalf("C1 findings for the generated list: %v", got)
	}
}
